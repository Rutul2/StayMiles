import useFetch from "../hooks/useFetch.js";

// Calls GET /listings/:id/safety. The server asks Gemini to pull safety keywords out of
// the reviews and score them from 1 to 10.
export default function SafetyScore({ listingId }) {
  const { data, loading, error } = useFetch(`/listings/${listingId}/safety`);

  return (
    <div className="panel insight">
      <h3>Safety score</h3>

      {loading && <p className="status">Analysing reviews…</p>}
      {error && <p className="error-text">{error}</p>}

      {data && !data.available && <p className="muted">{data.message}</p>}

      {data?.available && (
        <>
          <p className="insight-score">
            <strong>{data.score}</strong> <span className="muted">out of 10</span>
            <span className={`badge badge-${data.level}`}>{data.label}</span>
          </p>

          {/* The bar is just a div whose width is score x 10 percent */}
          <div className="meter" role="img" aria-label={`Safety score ${data.score} out of 10`}>
            <span className={`meter-fill meter-${data.level}`} style={{ width: `${data.score * 10}%` }} />
          </div>

          {data.reason && <p>{data.reason}</p>}

          {data.positiveKeywords.length > 0 && (
            <>
              <h4>Positive mentions</h4>
              <ul className="chips">{data.positiveKeywords.map((w) => <li key={w} className="chip chip-good">{w}</li>)}</ul>
            </>
          )}
          {data.negativeKeywords.length > 0 && (
            <>
              <h4>Concerns</h4>
              <ul className="chips">{data.negativeKeywords.map((w) => <li key={w} className="chip chip-bad">{w}</li>)}</ul>
            </>
          )}

          <p className="source-note">
            {data.source === "gemini"
              ? "Keywords and score generated by Google Gemini from guest reviews."
              : "Scored by keyword matching because the AI service was unavailable."}
          </p>
        </>
      )}
    </div>
  );
}
