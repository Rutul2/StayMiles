import useFetch from "../hooks/useFetch.js";

// Calls GET /listings/:id/summary. The server asks Gemini to summarise the reviews.
export default function ReviewSummary({ listingId }) {
  const { data, loading, error } = useFetch(`/listings/${listingId}/summary`);

  return (
    <div className="panel insight">
      <h3>Review summary</h3>

      {loading && <p className="status">Summarising reviews…</p>}
      {error && <p className="error-text">{error}</p>}

      {data && !data.available && <p className="muted">{data.message}</p>}

      {data?.available && (
        <>
          <p className="insight-score">
            <strong>{data.averageRating}</strong> <span className="muted">average from {data.reviewCount} reviews</span>
          </p>
          <p>{data.summary}</p>

          {data.guestsLove.length > 0 && (
            <>
              <h4>Guests love</h4>
              <ul className="chips">{data.guestsLove.map((item) => <li key={item} className="chip chip-good">{item}</li>)}</ul>
            </>
          )}
          {data.complaints.length > 0 && (
            <>
              <h4>Complaints</h4>
              <ul className="chips">{data.complaints.map((item) => <li key={item} className="chip chip-bad">{item}</li>)}</ul>
            </>
          )}
          {data.bestFor && (
            <>
              <h4>Best for</h4>
              <p>{data.bestFor}</p>
            </>
          )}

          <p className="source-note">
            {data.source === "gemini" ? "Generated by Google Gemini from guest reviews." : "AI summary is temporarily unavailable."}
          </p>
        </>
      )}
    </div>
  );
}
